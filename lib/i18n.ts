export function getDictionary(locale: Locale) {
  return dictionaries[locale];
}

export function getNavItems(locale: Locale) {
  return getDictionary(locale).nav.map((item) => ({
    ...item,
    href: localizePath(item.href, locale)
  }));
}

export function getLocalizedMetadata(locale: Locale, key: PageMetaKey, path: string): Metadata {
  const dict = getDictionary(locale);
  const meta = dict.metadata[key];
  const russianPath = localizePath(path, "ru");
  const kazakhPath = localizePath(path, "kk");

  return {
    title: meta.title,
    description: meta.description,
    keywords: commonKeywords,
    alternates: {
      canonical: localizePath(path, locale),
      languages: {
        ru: `${siteConfig.url}${russianPath}`,
        kk: `${siteConfig.url}${kazakhPath}`
      }
    },
    openGraph: {
      title: meta.title,
      description: meta.description,
      url: `${siteConfig.url}${localizePath(path, locale)}`
    }
  };
}

